import {availableParallelism} from 'node:os'
import {Worker} from 'node:worker_threads'
import {writeFile} from 'node:fs/promises'
import {prior} from '../src/bot-features.ts'

const requested=Number(process.argv[2]??192)
if(!Number.isInteger(requested)||requested<8||requested>4096)throw Error('Choose 8–4096 training games')
const threads=Math.max(1,Math.min(6,availableParallelism()-1,requested))
const seed=36259
const jobs=Array.from({length:threads},(_,index)=>new Promise((resolve,reject)=>{
  const games=Math.floor(requested/threads)+(index<requested%threads?1:0)
  const worker=new Worker(new URL('./bot-selfplay-worker.mjs',import.meta.url),{workerData:{index,workers:threads,games,plies:132,seed}})
  worker.once('message',resolve);worker.once('error',reject)
}))
const games=(await Promise.all(jobs)).flat()
const training=games.filter((_,i)=>i%6!==0).flatMap(g=>g.rows)
const validation=games.filter((_,i)=>i%6===0).flatMap(g=>g.rows)
const fitted=prior.slice()
const logistic=x=>1/(1+Math.exp(-x))
const p=(x,w)=>logistic(x.reduce((sum,value,i)=>sum+value*w[i],0)/470)
const loss=(rows,w)=>rows.reduce((sum,r)=>sum+(p(r.x,w)-r.y)**2,0)/rows.length

// Full-batch logistic training with a prior penalty and range constraints.
let best=fitted.slice(), bestLoss=loss(validation,best)
for(let round=0;round<260;round++){
  const grad=new Float64Array(prior.length)
  for(const row of training){
    const error=p(row.x,fitted)-row.y
    for(let i=0;i<fitted.length;i++)grad[i]+=error*row.x[i]
  }
  for(let i=0;i<fitted.length;i++){
    const penalty=(fitted[i]-prior[i])*(i<5?.12:.035)
    const update=(grad[i]*470/training.length+penalty)*.24
    const max=i<5?prior[i]*.27:Math.max(20,Math.abs(prior[i])*.63)
    const floor=prior[i]>0?Math.max(prior[i]-max,prior[i]*.25):prior[i]-max
    const ceiling=prior[i]<0?Math.min(prior[i]+max,prior[i]*.25):prior[i]+max
    fitted[i]=Math.max(floor,Math.min(ceiling,fitted[i]-update))
  }
  const validationError=loss(validation,fitted)
  if(validationError<bestLoss){bestLoss=validationError;best=fitted.slice()}
}
const weights=best.map(x=>Number(x.toFixed(2)))
const stats={games:games.length,completed:games.filter(x=>!x.cutoff).length,trainingPositions:training.length,validationPositions:validation.length,seed,priorError:loss(validation,prior),trainedError:loss(validation,weights)}
console.log(JSON.stringify({stats,weights}))
await writeFile(new URL('../src/bot-model.ts',import.meta.url),'// Generated by scripts/train-bot.mjs.\nexport const trainedWeights = '+JSON.stringify(weights)+'\nexport const trainingStats = '+JSON.stringify(stats)+'\n')
